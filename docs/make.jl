# Interactive figures: the examples use CairoMakie, and the pages WGLMakie. Bonito writes
# the JavaScript of the figures once, into a folder that is copied to the `public` folder of
# the site (at the same relative location as the pages that load it).
struct BonitoAssets <: Documenter.Plugin
    folder::String
end
DocumenterVitepress.vitepress_assets(assets::BonitoAssets) = [assets.folder]
bonito = BonitoAssets(mktempdir())
interactive = """
using WGLMakie # Or CairoMakie, GLMakie
using Bonito #hide
Bonito.Page(; current_page_dir = "$(joinpath(bonito.folder, "examples", "generated"))") #hide
nothing #hide
"""
outputdir = joinpath(@__DIR__, "src", "examples", "generated")
isdir(outputdir) && rm(outputdir; recursive = true)
for e in examples
    inputfile = joinpath(@__DIR__, "..", "examples", e.name * ".jl")
    preprocess(s) = replace(s, r"^using CairoMakie.*$"m => interactive)
    Literate.markdown(inputfile, outputdir; preprocess)
end

# The gallery page
open(joinpath(@__DIR__, "src", "examples", "index.md"), "w") do io
    println(io, "```@raw html")
    println(io, "<!-- Generated by docs/make.jl. Do not edit. -->")
    println(io, "<script setup lang=\"ts\">")
    for (i, category) in enumerate(categories)
        items = map(filter(e -> e.category == category, examples)) do e
            """
              {
                href: "generated/$(e.name)",
                src: "/gallery/$(e.name).png",
                caption: "$(e.title)",
                desc: "$(e.description)",
              },
            """
        end
        println(io, "const category$i = [\n", join(items), "];")
    end
    println(io, "</script>")
    println(io, "```")
    println(
        io,
        """

        # Examples

        Commented examples, each a script in the
        [`examples`](https://github.com/SpinDoctorMRI/SpinDoctor.jl/tree/main/examples)
        folder of the repository (with its own environment: `julia --project=examples`).
        The figures can be rotated and zoomed.
        """,
    )
    for (i, category) in enumerate(categories)
        println(io, "## $category\n")
        println(io, "```@raw html\n<Gallery :images=\"category$i\" />\n```\n")
    end
end

